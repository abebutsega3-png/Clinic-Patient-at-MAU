import mongoose from 'mongoose';

const clinicVisitSchema = new mongoose.Schema({
  visitId: { type: String, trim: true, default: undefined },
  patientRecordId: { type: mongoose.Schema.Types.ObjectId, ref: 'Patient', default: null, index: true },
  patientId: { type: String, required: true, trim: true },
  patientName: { type: String, required: true, trim: true },
  visitDate: { type: Date, default: Date.now, index: true },
  department: { type: String, trim: true, default: '' },
  visitType: { type: String, enum: ['New Visit', 'Follow-up Visit', 'Emergency Visit'], default: 'New Visit' },
  priority: { type: String, enum: ['Normal', 'Urgent', 'Emergency'], default: 'Normal' },
  status: { type: String, enum: ['Registered', 'Waiting', 'Called', 'In Service', 'Routed', 'Sent to Examination', 'Completed', 'Cancelled', 'No-show'], default: 'Registered' },
  idempotencyKey: { type: String, trim: true, default: undefined },
  registeredBy: { type: mongoose.Schema.Types.ObjectId, ref: 'User', default: null },
  diagnosis: { type: String, trim: true, default: '' },
  examination: {
    chiefComplaint: { type: String, trim: true, default: '' },
    historyOfPresentIllness: { type: String, trim: true, default: '' },
    vitals: {
      bloodPressure: { type: String, trim: true, default: '' },
      temperature: { type: String, trim: true, default: '' },
      pulse: { type: String, trim: true, default: '' },
      respiratoryRate: { type: String, trim: true, default: '' },
      weight: { type: String, trim: true, default: '' },
    },
    physicalExamination: { type: String, trim: true, default: '' },
    reviewOfSystem: { type: String, trim: true, default: '' },
    otherDiagnosis: { type: String, trim: true, default: '' },
    hmisDiagnosis: { type: String, trim: true, default: '' },
    doctorNotes: { type: String, trim: true, default: '' },
    patientCondition: { type: String, enum: ['Outpatient', 'Emergency', 'Non-emergency', 'Sick Leave', ''], default: '' },
    disposition: { type: String, enum: ['Discharge', 'Admit', 'Refer', 'Follow-up date', ''], default: '' },
    followUpDate: { type: String, trim: true, default: '' },
    prescriptionPatientType: { type: String, enum: ['inpatient', 'outpatient'], default: 'outpatient' },
    prescriptionStatus: { type: String, enum: ['Pending', 'Dispensed', 'Partially dispensed', 'Cancelled', ''], default: '' },
    prescriber: {
      name: { type: String, trim: true, default: '' },
      qualification: { type: String, trim: true, default: '' },
      registration: { type: String, trim: true, default: '' },
      signedAt: { type: Date, default: null },
    },
    prescriptionEvaluatedBy: { type: String, trim: true, default: '' },
    prescriptionEvaluatedAt: { type: Date, default: null },
    prescriptionAllergyReviewedBy: { type: String, trim: true, default: '' },
    prescriptionAllergyReviewedAt: { type: Date, default: null },
    prescriptionAllergyVerification: { type: String, enum: ['nka', 'known-allergies', ''], default: '' },
    prescriptionDispensedBy: { type: String, trim: true, default: '' },
    prescriptionDispensedAt: { type: Date, default: null },
    opd: {
      roadTrafficAccident: { type: Boolean, default: false },
      accidentType: { type: String, trim: true, default: '' },
      hivTestOffered: { type: Boolean, default: false },
      hivTestPerformed: { type: Boolean, default: false },
      hivResult: { type: String, trim: true, default: '' },
      targetPopulation: { type: String, trim: true, default: '' },
      tbScreened: { type: Boolean, default: false },
      tbResult: { type: String, trim: true, default: '' },
      diagnosticEvaluation: { type: String, trim: true, default: '' },
      referredTo: { type: String, trim: true, default: '' },
    },
    labRequests: [{
      testName: { type: String, trim: true, required: true },
      testCode: { type: String, trim: true, default: '' },
      priority: { type: String, enum: ['normal', 'urgent'], default: 'normal' },
      clinicalNote: { type: String, trim: true, default: '' },
      status: { type: String, enum: ['Pending', 'Sample Collected', 'In Progress', 'Results Ready', 'Reviewed', 'Rejected', 'Cancelled'], default: 'Pending' },
      result: { type: String, trim: true, default: '' },
      unit: { type: String, trim: true, default: '' },
      referenceRange: { type: String, trim: true, default: '' },
      flag: { type: String, trim: true, default: '' },
    }],
    labRequestNumber: { type: String, trim: true, default: '' },
    labStatus: { type: String, enum: ['Pending', 'Sample Collected', 'In Progress', 'Results Ready', 'Reviewed', ''], default: '' },
    labRequestedAt: { type: Date, default: null },
    labSampleCollectedAt: { type: Date, default: null },
    labInProgressAt: { type: Date, default: null },
    labResultReadyAt: { type: Date, default: null },
    labReviewedAt: { type: Date, default: null },
    labTestedBy: { type: String, trim: true, default: '' },
    labDateOfReport: { type: Date, default: null },
    labApprovedBy: { type: String, trim: true, default: '' },
    labApprovedAt: { type: Date, default: null },
    prescriptions: [{
      medicine: { type: String, trim: true, required: true },
      strength: { type: String, trim: true, default: '' },
      form: { type: String, trim: true, default: '' },
      dose: { type: String, trim: true, default: '' },
      dosage: { type: String, trim: true, default: '' },
      frequency: { type: String, trim: true, default: '' },
      duration: { type: String, trim: true, default: '' },
      quantity: { type: String, trim: true, default: '' },
      quantityUnit: { type: String, trim: true, default: '' },
      instructions: { type: String, trim: true, default: '' },
      priceCents: { type: Number, min: 0, default: 0 },
    }],
    referral: {
      department: { type: String, trim: true, default: '' },
      reason: { type: String, trim: true, default: '' },
      qualification: { type: String, trim: true, default: '' },
      emergency: { type: Boolean, default: false },
      ambulanceDriver: { type: String, trim: true, default: '' },
      takeOffTime: { type: String, trim: true, default: '' },
      remark: { type: String, trim: true, default: '' },
      referredAt: { type: Date, default: null },
    },
    sickLeaveDays: { type: Number, min: 0, max: 365, default: 0 },
  },
  waitTimeMinutes: { type: Number, min: 0, default: null },
  attendedByStaffId: { type: mongoose.Schema.Types.ObjectId, ref: 'Staff', default: null, index: true },
  emergency: { type: Boolean, default: false, index: true },
  emergencyResolved: { type: Boolean, default: false },
  referred: { type: Boolean, default: false }
}, { timestamps: true });

clinicVisitSchema.index({ visitDate: -1, emergency: 1, department: 1 });
clinicVisitSchema.index({ visitId: 1 }, { unique: true, sparse: true });
clinicVisitSchema.index({ idempotencyKey: 1 }, { unique: true, sparse: true });

const ClinicVisit = mongoose.models.ClinicVisit || mongoose.model('ClinicVisit', clinicVisitSchema);

export default ClinicVisit;
